using System.Buffers;
using System.Globalization;
using System.Security.Cryptography;
using System.Text.RegularExpressions;
using Microsoft.Extensions.Options;
using ODC.Web.Infrastructure.Tenancy;
using ODC.Web.Shared.Files;
using ODC.Web.Shared.Kernel;
using ODC.Web.Shared.Localization;

namespace ODC.Web.Infrastructure.Files;

/// <summary>
/// Stores private files on the local disk, encrypted (<see cref="EncryptedFile"/>): the files of an organization
/// (documents, signatures, chat attachments) under <c>{PrivateRoot}/orgs/{organization}/</c> with the organization's key,
/// those of the platform (requests to the support: <see cref="PlatformCategories"/>) under <c>{PrivateRoot}/platform/</c>
/// with the platform's key. The organization is the one of the unit of work, never one named by the request, so a key
/// of another organization opens nothing. Keys are generated by the storage and validated on every access, so client
/// input never becomes a path.
/// </summary>
internal sealed partial class LocalFileStorage : IFileStorage
{
    /// <summary>
    /// The categories of the platform's files.
    /// </summary>
    public static readonly IReadOnlySet<string> PlatformCategories = new HashSet<string>(StringComparer.Ordinal) { "tickets" };

    /// <summary>
    /// The absolute root folder.
    /// </summary>
    private readonly string _root;

    /// <summary>
    /// The clock.
    /// </summary>
    private readonly TimeProvider _timeProvider;

    /// <summary>
    /// The organization of the unit of work.
    /// </summary>
    private readonly OrganizationContext _organization;

    /// <summary>
    /// The keys of the files.
    /// </summary>
    private readonly FileKeys _keys;

    /// <summary>
    /// Initializes a new instance of the <see cref="LocalFileStorage"/> class.
    /// </summary>
    /// <param name="options">The storage options.</param>
    /// <param name="environment">The host environment.</param>
    /// <param name="timeProvider">The clock.</param>
    /// <param name="organization">The organization of the unit of work.</param>
    /// <param name="keys">The keys of the files.</param>
    public LocalFileStorage(IOptions<StorageOptions> options, IHostEnvironment environment, TimeProvider timeProvider, OrganizationContext organization, FileKeys keys)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(environment);

        _root = StorageOptions.RootOf(options.Value, environment);
        _timeProvider = timeProvider;
        _organization = organization;
        _keys = keys;
    }

    /// <inheritdoc />
    public async Task<StoredBlob> SaveAsync(Stream content, string category, long maxSize, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);
        if (!CategoryPattern().IsMatch(category))
        {
            throw new ArgumentException("Invalid storage category.", nameof(category));
        }

        var now = _timeProvider.GetUtcNow();
        var key = string.Create(CultureInfo.InvariantCulture, $"{category}/{now:yyyy}/{now:MM}/{Guid.CreateVersion7():N}");
        var (path, fileKey) = await ResolveAsync(key, cancellationToken);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var buffer = ArrayPool<byte>.Shared.Rent(81920);
        long size = 0;
        try
        {
            await using (var target = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, FileOptions.Asynchronous))
            {
                using var writer = EncryptedFile.Write(target, fileKey);
                int read;
                while ((read = await content.ReadAsync(buffer.AsMemory(0, buffer.Length), cancellationToken)) > 0)
                {
                    size += read;
                    if (size > maxSize)
                    {
                        throw new DomainException(Texts.T("Розмір файлу перевищує {0} МБ.", maxSize / 1024 / 1024));
                    }

                    // The digest is of the content (the browser checks it before signing), not of the encrypted file.
                    hash.AppendData(buffer, 0, read);
                    await writer.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
                }

                if (size == 0)
                {
                    throw new DomainException(Texts.T("Файл порожній."));
                }

                await writer.CompleteAsync(cancellationToken);
            }
        }
        catch
        {
            File.Delete(path);
            throw;
        }
        finally
        {
            ArrayPool<byte>.Shared.Return(buffer);
        }

        return new StoredBlob(key, size, Convert.ToHexStringLower(hash.GetHashAndReset()));
    }

    /// <inheritdoc />
    public async Task<Stream> OpenReadAsync(string storageKey, CancellationToken cancellationToken)
    {
        var (path, fileKey) = await ResolveAsync(storageKey, cancellationToken);
        if (!File.Exists(path))
        {
            // The same answer whether the folder or only the file is missing (another organization has no such folder).
            throw new FileNotFoundException("The stored file does not exist.", storageKey);
        }

        var file = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, FileOptions.Asynchronous | FileOptions.RandomAccess);
        return EncryptedFile.Read(file, fileKey);
    }

    /// <inheritdoc />
    public async Task DeleteAsync(string storageKey, CancellationToken cancellationToken)
    {
        var (path, _) = await ResolveAsync(storageKey, cancellationToken);
        if (File.Exists(path))
        {
            File.Delete(path);
        }
    }

    /// <summary>
    /// Matches storage categories.
    /// </summary>
    /// <returns>The regular expression.</returns>
    [GeneratedRegex("^[a-z]{1,32}$", RegexOptions.CultureInvariant)]
    private static partial Regex CategoryPattern();

    /// <summary>
    /// Matches storage keys produced by <see cref="SaveAsync"/>.
    /// </summary>
    /// <returns>The regular expression.</returns>
    [GeneratedRegex("^([a-z]{1,32})/[0-9]{4}/[0-9]{2}/[0-9a-f]{32}$", RegexOptions.CultureInvariant)]
    private static partial Regex KeyPattern();

    /// <summary>
    /// Converts a validated key into an absolute path inside the folder of its owner and gives the owner's key.
    /// </summary>
    /// <param name="storageKey">The key.</param>
    /// <param name="cancellationToken">The cancellation token.</param>
    /// <returns>The absolute path and the key of the file's owner.</returns>
    private async Task<(string Path, byte[] Key)> ResolveAsync(string storageKey, CancellationToken cancellationToken)
    {
        if (KeyPattern().Match(storageKey) is not { Success: true } match)
        {
            throw new ArgumentException("Invalid storage key.", nameof(storageKey));
        }

        string folder;
        byte[] key;
        if (PlatformCategories.Contains(match.Groups[1].Value))
        {
            folder = StorageOptions.PlatformFolder(_root);
            key = await _keys.PlatformAsync(cancellationToken);
        }
        else
        {
            var organization = _organization.Require();
            folder = StorageOptions.OrganizationFolder(_root, organization.Id);
            key = _keys.Of(organization);
        }

        var path = Path.GetFullPath(Path.Combine(folder, storageKey));
        return path.StartsWith(folder + Path.DirectorySeparatorChar, StringComparison.Ordinal)
            ? (path, key)
            : throw new ArgumentException("Invalid storage key.", nameof(storageKey));
    }
}
